    public static Localizer Instance { get; } = new();

    private string _lang = "fa";
    public string Language
    {
        get => _lang;
        set
        {
            if (Set(ref _lang, value))
            {
                Raise("Item[]");            // refresh every indexer binding
                OnChanged(nameof(IsRtl));
                OnChanged(nameof(AppFlow));
            }
        }
    }

    public bool IsRtl => _lang == "fa";
    public FlowDirection AppFlow => _lang == "fa" ? FlowDirection.RightToLeft : FlowDirection.LeftToRight;

    public void Toggle() => Language = _lang == "fa" ? "en" : "fa";

    public string this[string key]
    {
        get
        {
            var table = _lang == "fa" ? _fa : _en;
            return table.TryGetValue(key, out var v) ? v : key;
        }
    }

